#f Strings are being used when there is a need for concatenation between strings and other values


string_s0 = "Stefan"
string_s1 = "Marinkovic"

godine = 34

print(f"{string_s0} je {string_s1} i ima {godine} godina") # f-Strings

print("{} je {} i ima {} godina".format(string_s0, string_s1, godine)) #format option of manipulation with the data


